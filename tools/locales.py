#!/usr/bin/env python3
"""Localization (spec 16): translations from git -> LocaleData.luau (the Loc module; build.py) and the cloud table entries (loc_cloud.py).

The source is English: tests/loc_sources.luau outputs the path and text of every string (Strings without dragon names, the text fields of
Content, the Core/Quests quests). Translations - src/shared/locales/<lang>.csv, columns key, source, text: key - the path, source -
the English at the time of translation (the English changed - the translation is stale, it does not go into the game, the test fails), text - the translation.

    python3 roblox_game/tools/locales.py                 # LocaleData.luau + summary: how many are translated, stale, extra
    python3 roblox_game/tools/locales.py --missing es    # untranslated strings of a language (CSV on stdout: key, source, empty)
    python3 roblox_game/tools/locales.py --json          # the table for Open Cloud (entries as in LocalizationTable) on stdout
    python3 roblox_game/tools/locales.py --check         # check of the translations and the code; exit code 1 on an error
"""
import csv
import json
import math
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
LOCALES = os.path.join(GAME, "src", "shared", "locales")
OUT = os.path.join(GAME, "src", "shared", "LocaleData.luau")
LUAU = os.environ.get("LUAU", "luau")
# our checked languages; the rest - Roblox machine translation
LANGS = ("es", "pt", "de", "fr")
# the standard UI words - translated by the Roblox machine with its own words, we do not set our translation
STANDARD_FILE = os.path.join(LOCALES, "roblox_standard.txt")


def standard():
    if not os.path.exists(STANDARD_FILE):
        return set()
    return {l.strip() for l in open(STANDARD_FILE, encoding="utf-8") if l.strip() and not l.startswith("#")}


def unesc(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            out.append({"n": "\n", "t": "\t", "\\": "\\"}.get(s[i + 1], s[i + 1]))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def sources():
    """[(path, English)] in the export order."""
    r = subprocess.run([LUAU, os.path.join(GAME, "tests", "loc_sources.luau")], capture_output=True, text=True, cwd=GAME)
    if r.returncode != 0:
        sys.exit("loc_sources.luau: " + r.stderr.strip())
    rows = []
    for line in r.stdout.splitlines():
        if "\t" in line:
            k, v = line.split("\t", 1)
            rows.append((k, unesc(v)))
    return rows


def read_lang(lang):
    path = os.path.join(LOCALES, f"{lang}.csv")
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8", newline="") as f:
        return [(r["key"], r["source"], r["text"]) for r in csv.DictReader(f)]


def load():
    """Matching the translations against the source. -> (src [(path, English)], ok {lang: {path: translation}}, report {lang: {...}})."""
    src = sources()
    cur = dict(src)
    std = standard()
    need = sum(1 for _, en in src if en not in std)
    ok, report = {}, {}
    for lang in LANGS:
        good, stale, extra, empty, dup = {}, [], [], 0, []
        for key, source, text in read_lang(lang):
            if key not in cur:
                extra.append(key)
            elif source != cur[key]:
                stale.append(key)
            elif text.strip() == "":
                empty += 1
            elif source in std:
                dup.append(key)  # a standard word - the Roblox translation, ours is not needed
            else:
                good[key] = text
        ok[lang] = good
        report[lang] = {"done": len(good), "total": need, "stale": stale, "extra": extra, "empty": empty, "dup": dup}
    return src, ok, report


def luau_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def by_source(src, ok):
    """{lang: {English: translation}}; the same English on different paths - the first translation (the test requires them to be the same)."""
    out = {}
    for lang in LANGS:
        m = {}
        for key, en in src:
            t = ok[lang].get(key)
            if t is not None and en not in m:
                m[en] = t
        out[lang] = m
    return out


def write_luau(src, ok):
    data = by_source(src, ok)
    lines = ["--!strict", "-- GENERATED by roblox_game/tools/locales.py from src/shared/locales/<lang>.csv (spec 16) - do not edit by hand.",
             "-- Language -> the English source -> our translation. Read by the Loc module.", "local D: { [string]: { [string]: string } } = {}"]
    for lang in LANGS:
        lines.append(f"D.{lang} = {{")
        for en in sorted(data[lang]):
            lines.append(f"\t[{luau_str(en)}] = {luau_str(data[lang][en])},")
        lines.append("}")
    lines.append("return D")
    text = "\n".join(lines) + "\n"
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if old != text:
        open(OUT, "w", encoding="utf-8").write(text)
    return old != text


def table_entries(src, ok):
    """Cloud table entries: one per unique English (AutoLocalize looks up by Source), Key - the first path; the standard
    words (roblox_standard.txt) have no values of ours - the Roblox machine fills them."""
    data = by_source(src, ok)
    seen, entries = set(), []
    for key, en in src:
        if en in seen or en.strip() == "":
            continue
        seen.add(en)
        values = {lang: data[lang][en] for lang in LANGS if en in data[lang]}
        entries.append({"key": key, "context": "", "examples": "", "source": en, "values": values})
    return entries


PH = re.compile(r"\{(\w+)\}")
# the shop stop words (07 §9, Strings.Shop.banned) in our languages: purchase pressure is forbidden in the translation too
BANNED = {
    "es": ["compra ya", "última oportunidad", "date prisa", "apúrate", "tiempo limitado", "pide a tus padres", "solo hoy"],
    "pt": ["compre já", "última chance", "corra", "tempo limitado", "peça aos seus pais", "só hoje"],
    "de": ["jetzt kaufen", "letzte chance", "beeil dich", "begrenzte zeit", "frag deine eltern", "nur heute"],
    "fr": ["achète maintenant", "dernière chance", "dépêche-toi", "temps limité", "demande à tes parents", "aujourd'hui seulement"],
}
# translation length: not longer than English x1.4 (spec 16 §4), short strings - a margin of +6 characters
def max_len(en):
    return max(math.ceil(len(en) * 1.4), len(en) + 6)


def code_scan():
    """Template substitutions bypassing Loc: on the client - its own gsub by {x}, on the server - gsub by Strings.* (the text goes out in English)."""
    bad = []
    src = os.path.join(GAME, "src")
    for root, _, files in os.walk(src):
        for f in files:
            if not f.endswith(".luau") or f in ("Loc.luau", "Strings.luau", "LocaleData.luau"):
                continue
            path = os.path.join(root, f)
            rel = os.path.relpath(path, src)
            for i, line in enumerate(open(path, encoding="utf-8"), 1):
                if "loc-ok" in line: # a deliberate exception, the reason is in the line comment
                    continue
                code = line.split("--", 1)[0]
                if re.search(r'string\.gsub\([^)]*"\{\(%w\+\)\}"', code) and not rel.startswith("shared/Core/"):
                    bad.append(f"{rel}:{i} own template gsub")
                elif re.search(r"string\.gsub\(\s*Strings\.", code) or re.search(r"Strings\.fill\(", code):
                    bad.append(f"{rel}:{i} a substitution in Strings without Loc")
    return bad


def check():
    src, ok, report = load()
    errors, warns = [], []
    for lang in LANGS:
        r = report[lang]
        for k in r["stale"]:
            errors.append(f"{lang} {k}: the English changed - the translation is stale")
        for k in r["extra"]:
            errors.append(f"{lang} {k}: no such string in the source")
        for k in r["dup"]:
            errors.append(f"{lang} {k}: a standard word (roblox_standard.txt) - Roblox translates it, remove our translation")
        if r["done"] < r["total"]:
            errors.append(f"{lang}: translated {r['done']}/{r['total']}")
        seen = {}
        for key, en in src:
            t = ok[lang].get(key)
            if t is None:
                continue
            if sorted(PH.findall(t)) != sorted(PH.findall(en)):
                errors.append(f"{lang} {key}: placeholders {sorted(PH.findall(t))} vs {sorted(PH.findall(en))}")
            if len(t) > max_len(en):
                warns.append((len(t) / max(1, len(en)), f"{lang} {key}: {len(t)} characters vs {len(en)} ({t})"))
            if en in seen and seen[en] != t:
                errors.append(f"{lang} {key}: the same English is translated differently than elsewhere")
            seen.setdefault(en, t)
            if key.startswith("Strings.Shop.") or key.startswith("Strings.Buy."):
                low = t.lower()
                for b in BANNED[lang]:
                    if b in low:
                        errors.append(f"{lang} {key}: stop word '{b}'")
    errors += code_scan()
    for _, w in sorted(warns, reverse=True):
        print("LONG", w)
    for e in errors:
        print("ERROR", e)
    print(f"localization check: errors {len(errors)}, long {len(warns)} (a warning: what does not fit is decided by P8 - TextFits)")
    return 1 if errors else 0


def main():
    args = sys.argv[1:]
    src, ok, report = load()
    if args[:1] == ["--missing"]:
        lang = args[1]
        w = csv.writer(sys.stdout, lineterminator="\n")
        w.writerow(["key", "source", "text"])
        for key, en in src:
            if key not in ok[lang]:
                w.writerow([key, en, ""])
        return
    if args[:1] == ["--check"]:
        sys.exit(check())
    if args[:1] == ["--json"]:
        print(json.dumps(table_entries(src, ok), ensure_ascii=False))
        return
    changed = write_luau(src, ok)
    print(f"LocaleData.luau {'updated' if changed else 'unchanged'}; strings {len(src)}, unique {len(set(e for _, e in src))}")
    for lang in LANGS:
        r = report[lang]
        print(f"  {lang}: translated {r['done']}/{r['total']}, stale {len(r['stale'])}, extra {len(r['extra'])}, empty {r['empty']}"
              + (f"; stale: {', '.join(r['stale'][:5])}" if r["stale"] else ""))


if __name__ == "__main__":
    main()
